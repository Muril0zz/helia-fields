/**
 * Local prices and costs: official numbers at the finest level that exists for each crop
 * (municipality → state → country), then the farmer's own numbers on top.
 * Engine values are USD; everything shown to the farmer is in local currency.
 */
import { crop, type PriceTable } from '../engine';

type Level = 'farmer' | 'municipality' | 'state' | 'country' | 'global';

interface RawCrop {
  price?: number;
  price_period?: string;
  price_source?: string;
  cost?: number;
  cost_period?: string;
  cost_source?: string;
}
interface RawRegion {
  level: 'country' | 'state' | 'municipality';
  country: string;
  state?: string;
  municipality?: string;
  ibge?: string;
  currency: string;
  crops: Record<string, RawCrop>;
}
interface RawTable {
  generated: string;
  fx: Record<string, number | string>;
  regions: RawRegion[];
}

// the official table is generated by tools/fetch_prices.py; the app still works without it
const files = import.meta.glob<{ default: RawTable }>('./prices.json', { eager: true });
const TABLE: RawTable | null = Object.values(files)[0]?.default ?? null;

export interface Place {
  country: string; // ISO 3166-1 alpha-2, upper case
  state?: string; // e.g. MT
  municipality?: string;
  ibge?: string;
  label: string;
}

export interface Valued {
  value: number; // local currency (price per t, cost per ha)
  level: Level;
  source: string;
  period?: string;
  where?: string;
}

export interface LocalEconomics {
  place: Place | null;
  currency: string;
  fx: number; // local per USD
  crops: Record<string, { price: Valued; cost: Valued }>;
  /** USD table for the engine. */
  table: PriceTable;
  generated: string | null;
}

const norm = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim();

/** Currency per country (only where the table has local-currency data). */
function currencyFor(country: string | undefined): string {
  if (!country || !TABLE) return 'USD';
  const local = TABLE.regions.find((r) => r.country === country && r.currency !== 'USD');
  return local?.currency ?? 'USD';
}

function fxOf(code: string): number {
  if (code === 'USD') return 1;
  const v = TABLE?.fx[code];
  return typeof v === 'number' && v > 0 ? v : 1;
}

const where = (r: RawRegion) => [r.municipality, r.state, r.country].filter(Boolean).join(' · ');

/** Find the official value for one crop at the finest level available. */
function lookup(place: Place | null, id: string, field: 'price' | 'cost', currency: string, fx: number): Valued {
  const g = crop(id);
  const global: Valued = { value: (field === 'price' ? g.price : g.cost) * fx, level: 'global', source: 'Helia indicative global value' };
  if (!TABLE || !place) return global;
  const conv = (r: RawRegion, v: number) => (r.currency === currency ? v : r.currency === 'USD' ? v * fx : (v / fxOf(r.currency)) * fx);
  const pick = (r: RawRegion | undefined, level: Level): Valued | null => {
    const c = r?.crops[id];
    const v = c?.[field];
    if (!r || v === undefined || v === null || !Number.isFinite(v)) return null;
    return {
      value: conv(r, v),
      level,
      source: (field === 'price' ? c?.price_source : c?.cost_source) ?? '',
      period: field === 'price' ? c?.price_period : c?.cost_period,
      where: where(r),
    };
  };
  const inCountry = TABLE.regions.filter((r) => r.country === place.country);
  const muni = inCountry.find(
    (r) => r.level === 'municipality' && ((place.ibge && r.ibge === place.ibge) || (place.municipality && r.state === place.state && norm(r.municipality ?? '') === norm(place.municipality))),
  );
  const state = inCountry.find((r) => r.level === 'state' && r.state === place.state);
  // costs are surveyed in reference municipalities: use one from the same state when this one has none
  const sameStateRef = field === 'cost' ? inCountry.find((r) => r.level === 'municipality' && r.state === place.state && r.crops[id]?.cost !== undefined) : undefined;
  const country = inCountry.find((r) => r.level === 'country');
  return (
    pick(muni, 'municipality') ??
    pick(state, 'state') ??
    (sameStateRef ? pick(sameStateRef, 'municipality') : null) ??
    pick(country, 'country') ??
    global
  );
}

export type Overrides = Record<string, { price?: number; cost?: number }>; // local currency

export function localEconomics(place: Place | null, ids: string[], overrides: Overrides = {}): LocalEconomics {
  const currency = currencyFor(place?.country);
  const fx = fxOf(currency);
  const crops: LocalEconomics['crops'] = {};
  const table: PriceTable = {};
  for (const id of new Set(ids)) {
    const o = overrides[id] ?? {};
    const price: Valued = o.price !== undefined ? { value: o.price, level: 'farmer', source: 'farmer' } : lookup(place, id, 'price', currency, fx);
    const cost: Valued = o.cost !== undefined ? { value: o.cost, level: 'farmer', source: 'farmer' } : lookup(place, id, 'cost', currency, fx);
    crops[id] = { price, cost };
    table[id] = { price: price.value / fx, cost: cost.value / fx };
  }
  return { place, currency, fx, crops, table, generated: TABLE?.generated ?? null };
}

