/** A CAR code starts with the state and the IBGE municipality code: MT-5107925-… */
export function placeFromCar(code: string, municipalityName?: string): Place | null {
  const m = /^([A-Z]{2})-(\d{7})-/.exec(code);
  if (!m) return null;
  return { country: 'BR', state: m[1], ibge: m[2], municipality: municipalityName, label: `${municipalityName ? `${municipalityName} · ` : ''}${m[1]} · Brasil` };
}

/** Reverse geocode (OpenStreetMap Nominatim): only the coordinates leave the browser. */
export async function placeAt(lat: number, lon: number, signal?: AbortSignal): Promise<Place | null> {
  try {
    const r = await fetch(`https://nominatim.openstreetmap.org/reverse?format=jsonv2&zoom=10&lat=${lat.toFixed(4)}&lon=${lon.toFixed(4)}`, {
      signal,
      headers: { Accept: 'application/json' },
    });
    if (!r.ok) return null;
    const j = (await r.json()) as { address?: Record<string, string> };
    const a = j.address ?? {};
    const country = (a.country_code ?? '').toUpperCase();
    if (!country) return null;
    const iso = a['ISO3166-2-lvl4'] ?? a['ISO3166-2-lvl3'] ?? '';
    const state = iso.includes('-') ? iso.split('-')[1] : undefined;
    const municipality = a.municipality ?? a.city ?? a.town ?? a.village ?? a.county;
    return { country, state, municipality, label: [municipality, state, a.country].filter(Boolean).join(' · ') };
  } catch {
    return null;
  }
}

/** Brazilian grains are quoted per 60 kg bag, cotton per arroba (15 kg). */
export function priceUnit(id: string, currency: string): { label: string; perT: number } {
  if (currency === 'BRL') {
    if (id === 'cotton') return { label: '@ 15 kg', perT: 1000 / 15 };
    if (['soy', 'maize', 'sorghum', 'bean', 'cowpea', 'wheat', 'pmillet', 'rice', 'sunflower', 'canola', 'chickpea'].includes(id)) return { label: 'sc 60 kg', perT: 1000 / 60 };
  }
  return { label: 't', perT: 1 };
}
