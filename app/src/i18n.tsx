export const DICT: Record<Lang, Dict> = { en, pt };

export const LangContext = createContext<Lang>('en');

export function useLang(): Lang {
  return useContext(LangContext);
}

export function useT(): Dict {
  return DICT[useContext(LangContext)];
}

const PLACES_PT: [RegExp, string][] = [
  [/\bBrazil\b/g, 'Brasil'],
  [/\bUSA\b/g, 'EUA'],
  [/\bIndia\b/g, 'Índia'],
  [/\bKenya\b/g, 'Quênia'],
];

/** Country names in demo-site labels, localised. */
export function placeName(name: string, lang: Lang): string {
  return lang === 'pt' ? PLACES_PT.reduce((s, [re, to]) => s.replace(re, to), name) : name;
}

/** Browser language decides the first view; the toggle overrides it. */
export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('helia.lang');
    if (saved === 'en' || saved === 'pt') return saved;
  } catch {
    /* storage may be blocked */
  }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('pt') ? 'pt' : 'en';
}
